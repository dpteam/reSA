"""Generate source/game_sa/Scripts/OpcodeArity.gen.inc - the extracted arity table.

Every value is read out of refs/gtasa10us/gta_sa.exe by tools/opcode_arity.py; nothing here is invented.
The header it writes carries the same provenance, and the classification is deliberately conservative:
`-2` means "we could not determine this from the code", which the runtime treats as "do not skip".

Usage: python tools/gen_opcode_arity.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import opcode_arity as oa

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..',
                   'source', 'game_sa', 'Scripts', 'OpcodeArity.gen.inc')

VALUE_NONE = -1       # the command reads no operands at entry
VALUE_IRREGULAR = -2  # arity could not be determined from the code -> must not be auto-skipped


def build():
    table = {}
    for b in range(oa.NUM_DISPATCHERS):
        disp = oa.u32(oa.DISPATCHERS_VA, 4 * b)
        parsed = oa.parse_switch(disp)
        if parsed is None:
            raise SystemExit('dispatcher %#x failed to parse - refusing to emit a partial table' % disp)
        bound, sel, tgt = parsed
        base = oa.parse_actual_base(disp)
        if base is None:
            raise SystemExit('dispatcher %#x has no readable base - refusing to emit' % disp)
        cases = []
        for idx in range(bound + 1):
            s = oa.u8(sel, idx) if sel else idx
            cases.append((idx - base, oa.follow_thunk(oa.u32(tgt, 4 * s))))
        addrs = sorted({t for _o, t in cases})
        nxt = {a: (addrs[i + 1] if i + 1 < len(addrs) else None) for i, a in enumerate(addrs)}
        for op, t in cases:
            kind, n = oa.classify_case(t, nxt.get(t))
            v = n if kind == 'fixed' else (VALUE_NONE if kind == 'none' else VALUE_IRREGULAR)
            if op in table and table[op] != v:
                raise SystemExit('opcode %#x classified twice with different values (%d vs %d)'
                                 % (op, table[op], v))
            table[op] = v
    return table


def main():
    table = build()
    hi = max(table)
    fixed = sum(1 for v in table.values() if v >= 0)
    none_ = sum(1 for v in table.values() if v == VALUE_NONE)
    irr = sum(1 for v in table.values() if v == VALUE_IRREGULAR)

    lines = []
    lines.append('// AUTO-GENERATED by tools/gen_opcode_arity.py - DO NOT EDIT BY HAND.')
    lines.append('//')
    lines.append('// Source of every value: refs/gtasa10us/gta_sa.exe (GTA SA 1.0 US), read by')
    lines.append('// tools/opcode_arity.py. Nothing in this file is inferred from docs, memory or other')
    lines.append('// reimplementations, and the generator REFUSES to emit a partial table (it aborts if any')
    lines.append('// dispatcher fails to parse or states no base), so a value here means "the code says so".')
    lines.append('//')
    lines.append('// How the arity is obtained: nearly every dispatcher case begins')
    lines.append('//     6A <n> | 8B CE | E8 <call CRunningScript::CollectParameters>')
    lines.append('// so <n> is the number of operands the command consumes. Cases that collect with a')
    lines.append('// computed count, or collect more than once, are marked IRREGULAR rather than guessed.')
    lines.append('//')
    lines.append('//   >= 0        operands to consume')
    lines.append('//   %4d   the command reads no operands at entry (skipping is just \'continue\')' % VALUE_NONE)
    lines.append('//   %4d   undetermined - MUST NOT be auto-skipped (a wrong count desynchronises the' % VALUE_IRREGULAR)
    lines.append('//             instruction stream, which is worse than not running the command at all)')
    lines.append('//')
    lines.append('// Coverage: opcodes 0..%d; fixed=%d  reads-nothing=%d  irregular=%d.'
                 % (hi, fixed, none_, irr))
    lines.append('#pragma once')
    lines.append('')
    lines.append('#include <array>')
    lines.append('#include <cstdint>')
    lines.append('')
    lines.append('#include "eScriptCommands.h"   // for the eScriptCommands overload below')
    lines.append('')
    lines.append('namespace notsa::script {')
    lines.append('inline constexpr int16_t OPCODE_ARITY_NONE      = %d;' % VALUE_NONE)
    lines.append('inline constexpr int16_t OPCODE_ARITY_IRREGULAR = %d;' % VALUE_IRREGULAR)
    lines.append('inline constexpr uint32_t OPCODE_ARITY_COUNT    = %d;' % (hi + 1))
    lines.append('')
    lines.append('//! operands to consume for an opcode, or a negative sentinel (see above).')
    lines.append('inline constexpr std::array<int16_t, OPCODE_ARITY_COUNT> OPCODE_ARITY{{')

    row = []
    for op in range(hi + 1):
        row.append(str(table.get(op, VALUE_IRREGULAR)))
        if len(row) == 20:
            lines.append('    ' + ', '.join(row) + ',')
            row = []
    if row:
        lines.append('    ' + ', '.join(row) + ',')
    lines.append('}};')
    lines.append('')
    lines.append('//! True when the arity is known well enough to skip the command safely.')
    lines.append('constexpr bool OpcodeAritySkippable(uint32_t op) {')
    lines.append('    return op < OPCODE_ARITY_COUNT && OPCODE_ARITY[op] >= 0;')
    lines.append('}')
    lines.append('')
    lines.append('//! Operands for `command`, or a negative sentinel. Out-of-range ids are IRREGULAR by policy.')
    lines.append('constexpr int16_t OpcodeArityOf(uint32_t command) {')
    lines.append('    return command < OPCODE_ARITY_COUNT ? OPCODE_ARITY[command] : OPCODE_ARITY_IRREGULAR;')
    lines.append('}')
    lines.append('')
    lines.append('//! Overload so callers can pass the enum directly.')
    lines.append('constexpr int16_t OpcodeArityOf(eScriptCommands command) {')
    lines.append('    return OpcodeArityOf(static_cast<uint32_t>(command));')
    lines.append('}')
    lines.append('} // namespace notsa::script')

    path = os.path.abspath(OUT)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s' % path)
    print('  opcodes 0..%d  fixed=%d  none=%d  irregular=%d' % (hi, fixed, none_, irr))


if __name__ == '__main__':
    main()
